import puppeteer from 'puppeteer-core'
const b = await puppeteer.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox', '--autoplay-policy=no-user-gesture-required'] })
const p = await b.newPage()
p.on('console', (m) => m.type() === 'error' && console.log('console:', m.text()))
p.on('pageerror', (e) => console.log('pageerror', e.message))
await p.setViewport({ width: 1280, height: 900 })
await p.goto('http://localhost:3000', { waitUntil: 'networkidle0' })
const inp = await p.$('input[type=file]')
await inp.uploadFile(process.argv[2], ...(process.argv[3] ? [process.argv[3]] : []))
await p.evaluate(() => [...document.querySelectorAll('button')].find((x) => x.textContent.includes('EDM'))?.click())
await p.screenshot({ path: '/tmp/setup.png' })
await p.evaluate(() => [...document.querySelectorAll('button')].find((x) => x.textContent.startsWith('Master'))?.click())
await p.waitForFunction(() => /ready|failed/i.test(document.querySelector('h2')?.textContent || ''), { timeout: 120000 })
if (process.argv[3]) await p.evaluate(() => [...document.querySelectorAll('span')].find((x) => x.textContent === 'Details')?.click())
await new Promise((r) => setTimeout(r, 500))
console.log((await p.evaluate(() => document.querySelector('main').innerText)).slice(0, 2500))
await p.screenshot({ path: '/tmp/result.png', fullPage: true })
if (process.argv[3]) {
  await p.evaluate(() => [...document.querySelectorAll('button')].find((x) => x.textContent.includes('Download all'))?.click())
  await new Promise((r) => setTimeout(r, 300))
  await p.screenshot({ path: '/tmp/checkout.png' })
  console.log('MODAL:', await p.evaluate(() => document.querySelector('[role=dialog]')?.innerText))
}
await b.close()
